const { mkdirSync, readdirSync, readFileSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');
const { Script } = require('node:vm');

const root = join(__dirname, '..');
const sourceFiles = readdirSync(join(root, 'src'), { withFileTypes: true })
  .filter((entry) => entry.isFile() && entry.name.endsWith('.js'))
  .map((entry) => `src/${entry.name}`)
  .sort();
sourceFiles.push('コード.js');

const source = sourceFiles.map((file) => (
  `// ${file}\n${readFileSync(join(root, file), 'utf8').trimEnd()}`
)).join('\n\n');
const output = `// Generated by npm run build.\n\n${source}\n`;

new Script(output, { filename: 'dist/code.js' });
mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist', 'code.js'), output);
console.log('Generated dist/code.js');
